export type QvEvidence = NormalizedMetric | ReasonEvidence;

/** The one constructor the classifiers use, so every QV reason is a registered code. */
export function qvReason(
  code: string,
  polarity: ReasonCode['polarity'],
  evidence: readonly QvEvidence[] = [],
  params?: JsonObject,
): ReasonCode {
  if (QV_ALL_REASON_CODES.indexOf(code) < 0) throw new Error(`"${code}" is not a registered QV-v1.0 reason code.`);
  return createReason({ code, polarity, evidence, ...(params ? { params } : {}) });
}

/** Explanation text derived from the structured reasons (same objects the decision used). */
export function explainQvReasons(reasons: readonly ReasonCode[]): string[] {
  return explainReasons(reasons);
}
