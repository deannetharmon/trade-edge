// LEAPS-QV-0001 Gate 3 (Section 45.12) -- the QV-v1.0 reason-code registry.
//
// Reason codes are STRUCTURED evidence: the classifiers build them from the same comparisons that decide a state, and
// the explanation text is derived from the reason object itself (explainReasons), so a decision and its explanation
// cannot drift apart.
//
// Grammar deviation (reported): Gate 1's reason-code grammar requires a leading category (QUALITY / VALUATION /
// FUNDAMENTAL / TECHNICAL / RISK / DATA / LEAPS / LIFECYCLE). Three Section 45.12 names have no category prefix, so
// they are emitted with one; QV_SPEC_REASON_CONCEPTS maps every Section 45.12 name to the code actually emitted.

